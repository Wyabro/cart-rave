#!/usr/bin/env node
// PreToolUse guard — blocks writes to generated and archived files
// (AGENTS.md § WHAT'S OFF-LIMITS). These get hand-edited by accident because they
// read like ordinary docs; the generators then silently overwrite the edit, or
// health:check red-gates on the drift.
//
// Escape hatch: CART_CLASH_SKIP_HOOKS=1 or SKIP_PATH_GUARD=1, read from this
// process's own env (never parsed out of a command string) — e.g. for resolving a
// merge conflict inside docs/ARCHITECTURE.json by hand.
//
// Fails open by design: any parse or logic error exits 0.

import path from 'node:path';

// Keys are lowercased repo-relative paths — Windows paths are case-insensitive.
const EXACT = new Map([
  [
    'docs/briefing.md',
    'docs/BRIEFING.md is generated by `npm run briefing` and committed. Edit docs/STATUS.md, ' +
      'then regenerate — `briefing:check` / `health:check` fail when BRIEFING lags STATUS.',
  ],
  [
    'docs/architecture.json',
    'docs/ARCHITECTURE.json is generated by `npm run arch`. Curate the system taxonomy in ' +
      'tools/lib/archMap.mjs, then regenerate.',
  ],
]);

const PREFIXES = new Map([
  ['docs/archive/handovers/', 'docs/archive/handovers/ is a historical archive — do not edit.'],
  ['docs/archive/audits/', 'docs/archive/audits/ is a historical archive — do not edit.'],
]);

/**
 * Decide whether a Write/Edit tool call targets a protected path.
 * Pure — exported for tests/claudeHooks.test.js.
 * @param {{ tool_input?: { file_path?: string, notebook_path?: string }, cwd?: string }} input
 * @param {Record<string, string | undefined>} env
 * @returns {string | null} denial reason, or null to allow
 */
export function evaluateProtectedPath(input, env = {}) {
  if (env.CART_CLASH_SKIP_HOOKS || env.SKIP_PATH_GUARD) return null;

  const target = input?.tool_input?.file_path ?? input?.tool_input?.notebook_path;
  if (typeof target !== 'string' || !target) return null;

  const root = env.CLAUDE_PROJECT_DIR || input?.cwd || process.cwd();
  const rel = path
    .relative(root, path.resolve(root, target))
    .split(path.sep)
    .join('/')
    .toLowerCase();

  // Outside the project tree — not ours to police.
  if (rel.startsWith('../')) return null;

  const exact = EXACT.get(rel);
  if (exact) return exact;

  for (const [prefix, reason] of PREFIXES) {
    if (rel.startsWith(prefix)) return reason;
  }
  return null;
}

function deny(reason) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason: `Blocked by .claude/hooks/guard-protected-paths.mjs. ${reason}`,
      },
    })
  );
}

async function main() {
  let raw = '';
  process.stdin.setEncoding('utf8');
  for await (const chunk of process.stdin) raw += chunk;

  const reason = evaluateProtectedPath(JSON.parse(raw), process.env);
  if (reason) deny(reason);
}

const isMain =
  process.argv[1] && /guard-protected-paths\.mjs$/.test(process.argv[1].replace(/\\/g, '/'));

if (isMain) {
  try {
    await main();
  } catch {
    // Fail open — never block on a bug in this guard.
  }
  process.exit(0);
}
